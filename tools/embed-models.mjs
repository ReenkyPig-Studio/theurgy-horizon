import fs from 'node:fs/promises';
import path from 'node:path';
import {root} from './common.mjs';

async function entries(dir){const out=[];for(const name of (await fs.readdir(dir)).sort()){if(!name.endsWith('.json'))continue;const text=await fs.readFile(path.join(dir,name),'utf8');out.push(`    (${JSON.stringify(name)}, ${JSON.stringify(text)}),`);}return out;}
const models=await entries(path.join(root,'native/theurgy/data/models'));
const animations=await entries(path.join(root,'native/theurgy/data/animations'));
const rust='// SPDX-License-Identifier: MIT\n// Generated by tools/embed-models.mjs from the pinned CC-BY-4.0 assets.\n\npub const MODELS: &[(&str, &str)] = &[\n'+models.join('\n')+'\n];\n\npub const ANIMATIONS: &[(&str, &str)] = &[\n'+animations.join('\n')+'\n];\n';
await fs.writeFile(path.join(root,'native/theurgy/model_data.rs'),rust);
console.log(JSON.stringify({models:models.length,animations:animations.length,bytes:Buffer.byteLength(rust)}));
